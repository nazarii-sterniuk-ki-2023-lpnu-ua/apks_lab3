library IEEE;
use IEEE.STD_LOGIC_1164.ALL;

-- ?????? ???????? (Rx) ??? SPI
entity spi_rx is
    Port (
        clk         : in  STD_LOGIC; -- ????????? ???????? ??????
        reset       : in  STD_LOGIC; -- ?????????? ????????
        sample_en   : in  STD_LOGIC; -- ?????? ?????????? ???? (??????????? ??? SCK)
        miso        : in  STD_LOGIC; -- ?????? ?????????? ????? ??? Slave
        rx_data_out : out STD_LOGIC_VECTOR(7 downto 0) -- ??????? 8-????? ????
    );
end spi_rx;

architecture Behavioral of spi_rx is
    -- ?????????? ??????? ??????? ??? ??????? ?????
    signal shift_reg : STD_LOGIC_VECTOR(7 downto 0) := (others => '0');
begin
    -- ????? ???????? ????? ?? ????????? ????
    rx_data_out <= shift_reg;

    process(clk, reset)
    begin
        if reset = '1' then
            shift_reg <= (others => '0');
        elsif rising_edge(clk) then
            if sample_en = '1' then
                -- ?????????? ???? ? MISO ?? ???? ???????? ?????
                shift_reg <= shift_reg(6 downto 0) & miso;
            end if;
        end if;
    end process;
end Behavioral;