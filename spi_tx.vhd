library IEEE;
use IEEE.STD_LOGIC_1164.ALL;

-- ?????? ?????????? (Tx) ??? SPI
entity spi_tx is
    Port (
        clk         : in  STD_LOGIC; -- ????????? ???????? ??????
        reset       : in  STD_LOGIC; -- ?????????? ???????? (???????? ???????)
        tx_start    : in  STD_LOGIC; -- ?????? ???????????? ????? ?????
        shift_en    : in  STD_LOGIC; -- ?????? ????? (??????????? ??? SCK)
        tx_data_in  : in  STD_LOGIC_VECTOR(7 downto 0); -- ?????? 8-????? ????
        mosi        : out STD_LOGIC  -- ??????? ?????????? ????? ?????
    );
end spi_tx;

architecture Behavioral of spi_tx is
    -- ?????????? ??????? ??????? ??? ?????????? ?? ???????? ?????
    signal shift_reg : STD_LOGIC_VECTOR(7 downto 0) := (others => '0');
begin
    -- ????? MOSI ?????? ?????????? ?? ???????? ???? (MSB) ???????? ????????
    mosi <= shift_reg(7);

    process(clk, reset)
    begin
        if reset = '1' then
            shift_reg <= (others => '0');
        elsif rising_edge(clk) then
            if tx_start = '1' then
                -- ?????????? ???????????? ????? ????? ???????? ????????
                shift_reg <= tx_data_in;
            elsif shift_en = '1' then
                -- ???????? ???? ?????. ???????? ??? ???????????? ?????.
                shift_reg <= shift_reg(6 downto 0) & '0';
            end if;
        end if;
    end process;
end Behavioral;